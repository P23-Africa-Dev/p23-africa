def php_str(value):
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def php_val(value, indent):
    pad = " " * indent
    if isinstance(value, str):
        return php_str(value)
    if isinstance(value, list):
        lines = ["["]
        for item in value:
            lines.append(pad + "    " + php_val(item, indent + 4) + ",")
        lines.append(pad + "]")
        return "\n".join(lines)
    raise TypeError(type(value))


def append_lang(rel, keys):
    path = ROOT / rel
    text = path.read_text(encoding="utf-8")
    marker = next(iter(keys))
    if "'" + marker + "'" in text:
        print("skip", rel)
        return
    idx = text.rfind("];")
    if idx < 0:
        raise SystemExit("no close " + rel)
    lines = []
    for key, value in keys.items():
        lines.append("    " + php_str(key) + " => " + php_val(value, 4) + ",")
    path.write_text(text[:idx] + "\n" + "\n".join(lines) + "\n" + text[idx:], encoding="utf-8")
    print("append", rel, len(keys))


def replace_in(rel, pairs):
    path = ROOT / rel
    text = path.read_text(encoding="utf-8")
    for old, new in pairs:
        count = text.count(old)
        if count == 0:
            print("MISS", rel, old[:80].replace("\n", " "))
            continue
        text = text.replace(old, new)
        print("OK", count, rel, old[:60].replace("\n", " ").encode("ascii", "replace").decode())
    path.write_text(text, encoding="utf-8")


